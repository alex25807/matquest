export const getPuzzlesForLevel = (level: number): Question[] => {
  return puzzles.filter(p => p.level <= level + 1);
};

export const getRandomPuzzles = (level: number, count: number = 5): Question[] => {
  const available = getPuzzlesForLevel(level);
  return available.sort(() => Math.random() - 0.5).slice(0, count);
};
