const METHOD =
  'Вспомни, сколько мелких единиц в одной крупной. Переведи всё в одну единицу и только потом сложи, вычти или раздели.';

function prep(n: number, one: string, many: string): string {
  const n10 = Math.abs(n) % 10;
  const n100 = Math.abs(n) % 100;
  return `${n} ${n10 === 1 && n100 !== 11 ? one : many}`;
}

function timesWord(n: number): string {
  const n10 = Math.abs(n) % 10;
  const n100 = Math.abs(n) % 100;
  if (n10 >= 2 && n10 <= 4 && (n100 < 12 || n100 > 14)) return 'раза';
  return 'раз';
}

function partsPhrase(n: number): string {
  const n10 = Math.abs(n) % 10;
  const n100 = Math.abs(n) % 100;
  if (n10 === 1 && n100 !== 11) return `${n} равную часть`;
  if (n10 >= 2 && n10 <= 4 && (n100 < 12 || n100 > 14)) return `${n} равные части`;
  return `${n} равных частей`;
}

function metersAndCm(totalCm: number): string {
  const m = Math.floor(totalCm / 100);
  const cm = totalCm % 100;
  if (m === 0) return `${cm} см`;
  if (cm === 0) return `${m} м`;
  return `${m} м ${cm} см`;
}

function kgAndG(totalG: number): string {
  const kg = Math.floor(totalG / 1000);
  const g = totalG % 1000;
  if (kg === 0) return `${g} г`;
  if (g === 0) return `${kg} кг`;
  return `${kg} кг ${g} г`;
}

function clockLabel(totalMin: number): string {
  const h = Math.floor(totalMin / 60);
  const m = totalMin % 60;
  if (m === 0) return `${h} ч ровно`;
  return `${h} ч ${m} мин`;
}

function item(
  templateId: string,
  text: string,
  answer: number,
  hints: [string, string],
  explanation: string,
  alternativeSolutions?: string[]
): ReturnType<TemplateFn> {
  return {
    templateId,
    text,
    answer,
    hint: hints[0],
    hints,
    method: METHOD,
    explanation,
    alternativeSolutions,
  };
}

