function templatesFor(kind: MeasureKind, tier: Tier): TemplateFn[] {
  if (kind === 'time') return timeTemplates(tier);
  if (kind === 'length') return lengthTemplates(tier);
  if (kind === 'mass') return massTemplates(tier);
  return areaTemplates(tier);
}

export function generateMeasuresQuestion(
  tier: Tier,
  excludeTemplateId?: string | null,
  drill?: MeasuresDrillState | null
): { question: AdaptiveQuestion; measures: MeasuresDrillState } {
  const index = drill && drill.nextKind >= 0 && drill.nextKind < KINDS.length ? drill.nextKind : 0;
  const kind = KINDS[index];
  const question = withMeta('measures', tier, pickTemplate(templatesFor(kind, tier), excludeTemplateId));
  return { question, measures: { nextKind: (index + 1) % KINDS.length } };
}
